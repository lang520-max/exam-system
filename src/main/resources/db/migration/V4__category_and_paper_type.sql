-- ============================================================================
--  V4 —— 专题/类型：题目的知识点 + 试卷的类型
--
--  需求原话：「增加试卷类型，例如高数的一元函数积分学的专项训练，
--            还有英语的语法练习」。
--
--  两个字段各解决一半问题（缺一个都做不成那两种「专项」）：
--    · question.category —— 题目级「知识点/专题」（如「一元函数积分学」「语法」）。
--      没有它就无法按专题**抽题**：专项训练卷抽不出来，自由练习也没法只练一个专题。
--    · exam.paper_type   —— 试卷级「类型」（模拟卷 / 专项训练）。用来在列表里分类展示，
--      与 title 里的专题名互补（专题名承载在标题上，类型承载「这是哪一类卷子」）。
--
--  设计取舍：
--    · 都用字符串而不是数字枚举：这两项是**展示与检索**用的标签，
--      排障时一眼看得懂，以后加类型也不用改语义（与 face_verify_log.result 同一考虑）。
--    · category 可空：老数据/导入漏填不该阻塞（题型、难度才是抽题的硬约束）。
--    · paper_type 不可空、默认「模拟卷」：现有 12 张卷子都是模拟卷，
--      默认值让老数据与老客户端（不带这个字段的导入 JSON）行为不变。
--    · 加索引：按知识点筛题是高频操作（题库管理筛选、专项抽题都要走）。
-- ============================================================================

ALTER TABLE `question`
    ADD COLUMN `category` VARCHAR(50) DEFAULT NULL
    COMMENT '知识点/专题：如「一元函数积分学」「语法」；专项训练与自由练习按它抽题'
    AFTER `analysis`;

ALTER TABLE `exam`
    ADD COLUMN `paper_type` VARCHAR(20) NOT NULL DEFAULT '模拟卷'
    COMMENT '试卷类型：模拟卷 / 专项训练'
    AFTER `pass_score`;

CREATE INDEX `idx_question_category` ON `question` (`category`);